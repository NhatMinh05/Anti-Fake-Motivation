export function getTranslation(key) {
  const lang = localStorage.getItem('sys_lang') || 'en';
  return dictionary[lang][key] || key;
}

export function applyTranslations() {
  // 1. Dịch các đoạn text thông thường
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = getTranslation(key);
  });

  // 2. Dịch các ô nhập liệu (Placeholder)
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', getTranslation(key));
  });
}

export function setLanguage(langCode) {
  localStorage.setItem('sys_lang', langCode);
  applyTranslations(); // Dịch ngay lập tức cho các phần tử tĩnh
  
  // Phát sự kiện để các Component động biết mà vẽ lại
  window.dispatchEvent(new CustomEvent('language-changed', { detail: langCode }));
}

